/**
 * Extracts an assignee name from task text if formatted as (Assignee: Name) or [@Name]
 * @param {string} text 
 * @returns {string|null}
 */
export function extractAssignee(text) {
  if (!text || typeof text !== 'string') return null;
  const match = text.match(/\((?:Assignee|Owner):\s*([^)]+)\)/i) ||
                text.match(/\[@([^\]]+)\]/i) ||
                text.match(/\[(?:Assignee|Owner):\s*([^\]]+)\]/i);
  return match ? match[1].trim() : null;
}

/**
 * Encodes query parameters using RFC 3986 encodeURIComponent (%20 for spaces)
 * @param {Record<string, string|number|boolean>} params 
 * @returns {string}
 */
function toQueryString(params) {
  return Object.entries(params)
    .filter(([, val]) => val !== undefined && val !== null && val !== '')
    .map(([key, val]) => `${encodeURIComponent(key)}=${encodeURIComponent(String(val))}`)
    .join('&');
}

/**
 * Builds the GitHub Issue payload (title, markdown body, labels) for an action item
 * @param {string|object} task 
 * @param {object} [meetingContext]
 * @returns {{ title: string, body: string, labels: string[] }}
 */
export function buildGitHubIssuePayload(task, meetingContext = {}) {
  const isObj = task && typeof task === 'object';
  const rawText = isObj ? (task.text || task.title || '') : String(task || '');
  const assignee = isObj ? (task.assignee || extractAssignee(rawText)) : extractAssignee(rawText);
  const due = isObj ? task.due : null;

  const meetingTitle = meetingContext.title || 'Executive Session';
  const meetingDate = meetingContext.date || new Date().toISOString().split('T')[0];
  const meetingId = meetingContext.meetingId ? ` (ID: ${meetingContext.meetingId})` : '';

  const cleanText = rawText
    .replace(/\((?:Assignee|Owner):\s*[^)]+\)/gi, '')
    .replace(/\[@[^\]]+\]/gi, '')
    .trim();

  const title = `[Action Item] ${cleanText || rawText || 'Untitled Task'}`;

  const bodyLines = [
    `### AI Action Item`,
    ``,
    `**Task:** ${cleanText || rawText}`,
    assignee ? `**Assignee:** ${assignee}` : null,
    due ? `**Due Date:** ${due}` : null,
    ``,
    `---`,
    `*Generated by AI Meeting Assistant from meeting: "${meetingTitle}" on ${meetingDate}${meetingId}*`
  ].filter(line => line !== null);

  return {
    title,
    body: bodyLines.join('\n'),
    labels: ['deliverable', 'ai-action-item']
  };
}

/**
 * Generates an instant GitHub New Issue URL for zero-token browser creation
 * @param {string} repo - Repository in "owner/repo" format
 * @param {object} payload - { title, body, labels }
 * @returns {string}
 */
export function buildGitHubIssueUrl(repo, payload = {}) {
  const sanitizedRepo = (repo || 'org/repo').trim().replace(/^\/+|\/+$/g, '');
  const params = {};

  if (payload.title) {
    params.title = payload.title;
  }
  if (payload.body) {
    params.body = payload.body;
  }
  if (Array.isArray(payload.labels) && payload.labels.length > 0) {
    params.labels = payload.labels.join(',');
  }

  const query = toQueryString(params);
  return `https://github.com/${sanitizedRepo}/issues/new${query ? '?' + query : ''}`;
}

/**
 * Builds a Gmail Web composer URL or mailto: link for executive minute dispatch
 * @param {object} options
 * @param {string|string[]} options.to
 * @param {string} options.subject
 * @param {string} options.body
 * @param {'web'|'mailto'} [options.format='web']
 * @returns {string}
 */
export function buildGmailDispatchUrl({ to = '', subject = '', body = '', format = 'web' }) {
  const recipients = Array.isArray(to) ? to.filter(Boolean).join(',') : String(to || '').trim();

  if (format === 'mailto') {
    const params = {};
    if (subject) params.subject = subject;
    if (body) params.body = body;
    const qs = toQueryString(params);
    return `mailto:${encodeURIComponent(recipients)}${qs ? '?' + qs : ''}`;
  }

  // Gmail Web interface
  const params = {
    view: 'cm',
    fs: '1'
  };
  if (recipients) params.to = recipients;
  if (subject) params.su = subject;

  let finalBody = body;
  if (finalBody) {
    const truncationSuffix = '\n\n[Full minutes copied to clipboard. Truncated for URL length limit]';
    const initialUrl = `https://mail.google.com/mail/?${toQueryString({ ...params, body: finalBody })}`;

    if (initialUrl.length > 2000) {
      const emptyBodyUrl = `https://mail.google.com/mail/?${toQueryString({ ...params, body: '' })}`;
      const maxEncodedBodyLen = Math.max(0, 2000 - emptyBodyUrl.length);
      const suffixEncoded = encodeURIComponent(truncationSuffix);
      const availableForPrefix = maxEncodedBodyLen - suffixEncoded.length;

      if (availableForPrefix > 0) {
        let sliceLen = Math.min(finalBody.length, availableForPrefix);
        let candidate = finalBody.slice(0, sliceLen);
        while (encodeURIComponent(candidate).length > availableForPrefix && sliceLen > 0) {
          sliceLen = Math.max(0, sliceLen - 10);
          candidate = finalBody.slice(0, sliceLen);
        }
        finalBody = candidate + truncationSuffix;
      } else {
        finalBody = truncationSuffix;
      }

      while (`https://mail.google.com/mail/?${toQueryString({ ...params, body: finalBody })}`.length > 2000 && finalBody.length > truncationSuffix.length) {
        finalBody = finalBody.slice(0, finalBody.length - truncationSuffix.length - 1) + truncationSuffix;
      }
    }
    params.body = finalBody;
  }

  return `https://mail.google.com/mail/?${toQueryString(params)}`;
}

/**
 * Formats meeting minutes into an Executive Brief or Comprehensive Report
 * @param {object} meetingData
 * @param {object} [options]
 * @param {'brief'|'comprehensive'} [options.template='brief']
 * @returns {string}
 */
export function formatEmailMinutes(meetingData = {}, { template = 'brief' } = {}) {
  const title = meetingData.title || 'Executive Session';
  const date = meetingData.date || new Date().toISOString().split('T')[0];
  const summary = meetingData.summary || 'Summary not available.';
  const decisions = Array.isArray(meetingData.keyDecisions) ? meetingData.keyDecisions : [];
  const risks = Array.isArray(meetingData.risks) ? meetingData.risks : [];
  const actions = Array.isArray(meetingData.actionItems) ? meetingData.actionItems : [];
  const attendees = Array.isArray(meetingData.attendees) ? meetingData.attendees.filter(Boolean).join(', ') : '';

  if (template === 'brief') {
    const lines = [
      `EXECUTIVE BRIEFING: ${title}`,
      `Date: ${date}`,
      ``,
      `EXECUTIVE SUMMARY:`,
      summary,
      ``
    ];

    if (decisions.length > 0) {
      lines.push(`KEY DECISIONS:`);
      decisions.forEach(d => lines.push(`• ${d}`));
      lines.push(``);
    }

    lines.push(`---`);
    lines.push(`Generated by AI Meeting Assistant · For complete notes and audio, open workspace.`);
    return lines.join('\n');
  }

  // Comprehensive template
  const lines = [
    `COMPREHENSIVE MEETING MINUTES: ${title}`,
    `Date: ${date}`,
    attendees ? `ATTENDEES: ${attendees}` : null,
    ``,
    `EXECUTIVE SUMMARY:`,
    summary,
    ``
  ].filter(line => line !== null);

  if (decisions.length > 0) {
    lines.push(`KEY DECISIONS:`);
    decisions.forEach(d => lines.push(`• ${d}`));
    lines.push(``);
  }

  if (risks.length > 0) {
    lines.push(`IDENTIFIED RISKS & BLOCKERS:`);
    risks.forEach(r => lines.push(`• ${r}`));
    lines.push(``);
  }

  if (actions.length > 0) {
    lines.push(`ACTION ITEMS & DELIVERABLES:`);
    actions.forEach(a => {
      const isObj = a && typeof a === 'object';
      const text = isObj ? (a.text || a.title || '') : String(a);
      const assignee = isObj ? a.assignee : extractAssignee(text);
      const assigneeStr = assignee ? ` (Assignee: ${assignee})` : '';
      lines.push(`[ ] ${text}${assigneeStr}`);
    });
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`Dispatched via AI Meeting Assistant Executive Hub.`);
  return lines.join('\n');
}

/**
 * Direct GitHub REST API dispatch when user configures a Personal Access Token in localStorage
 * @param {object} options
 * @param {string} options.repo - "owner/repo"
 * @param {string} options.token - GitHub PAT
 * @param {object} options.payload - { title, body, labels }
 * @returns {Promise<object>}
 */
export async function postGitHubIssue({ repo, token, payload }) {
  if (!repo || !repo.includes('/')) {
    throw new Error('Please enter a valid GitHub repository in "owner/repo" format.');
  }
  if (!token) {
    throw new Error('GitHub Personal Access Token is required for direct API creation.');
  }

  const cleanRepo = repo.trim().replace(/^\/+|\/+$/g, '');
  const url = `https://api.github.com/repos/${cleanRepo}/issues`;

  const response = await fetch(url, {
    method: 'POST',
    headers: {
      'Accept': 'application/vnd.github+json',
      'Authorization': `Bearer ${token.trim()}`,
      'X-GitHub-Api-Version': '2022-11-28',
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      title: payload.title,
      body: payload.body,
      labels: payload.labels || []
    })
  });

  if (!response.ok) {
    let errMessage = `GitHub API error: HTTP ${response.status} ${response.statusText}`;
    try {
      const errJson = await response.json();
      if (errJson && errJson.message) {
        errMessage = `GitHub API: ${errJson.message}`;
      }
    } catch {
      // ignore json parse error on error response
    }
    throw new Error(errMessage);
  }

  return response.json();
}
